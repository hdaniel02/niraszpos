          bottom: 24,
          child: Container(
            width: 3,
            color: Colors.grey.shade200,
          ),
        ),
        // The dynamic green timeline line that fills on scroll
        Positioned(
          left: 38.5,
          top: 24,
          bottom: 24,
          child: LayoutBuilder(
            builder: (context, constraints) {
              return Column(
                children: [
                  Container(
