  // ── Sales Overview Bar Chart ──────────────────────────────────────────────
  Widget _buildSalesOverviewChart(InsightsData data) {
    List<BarChartGroupData> barGroups = [];
    double maxY = 0;
    
    for (int i = 0; i < 6; i++) {
      double rev = 0;
      for (int j = 0; j < 5; j++) {
        int index = (i * 5) + j;
        if (index < data.dailyRevenues.length) rev += data.dailyRevenues[index];
      }
      if (rev > maxY) maxY = rev;
      
      double target = rev * 1.3; 
      if (target > maxY) maxY = target;

      barGroups.add(
        BarChartGroupData(
          x: i,
          barRods: [
            BarChartRodData(
              toY: target == 0 ? 10 : target,
              color: targetGrey,
              width: 12,
              borderRadius: BorderRadius.circular(4),
            ),
            BarChartRodData(
              toY: rev,
              color: primaryGreen,
              width: 12,
              borderRadius: BorderRadius.circular(4),
            ),
          ],
        ),
      );
    }
    
    maxY = maxY == 0 ? 100 : maxY * 1.2;

    return Container(
      height: 400,
      padding: const EdgeInsets.all(24),
      decoration: BoxDecoration(
        color: cardBg,
        borderRadius: BorderRadius.circular(16),
        border: Border.all(color: borderColor, width: 1),
      ),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Row(
            mainAxisAlignment: MainAxisAlignment.spaceBetween,
            children: [
              const Flexible(child: Text('Sales Trend & Forecast', style: TextStyle(fontSize: 18, fontWeight: FontWeight.bold, color: textDark))),
              Row(
                mainAxisSize: MainAxisSize.min,
                children: [
                  _buildLegendItem('Historical', targetGrey),
                  const SizedBox(width: 12),
                  _buildLegendItem('AI Predicted', primaryGreen),
                ],
              )
            ],
          ),
          const SizedBox(height: 12),
          Wrap(
            crossAxisAlignment: WrapCrossAlignment.center,
            spacing: 12,
            runSpacing: 8,
            children: [
              Text('RM ${data.totalRevenue.toStringAsFixed(2)}', style: const TextStyle(fontSize: 32, fontWeight: FontWeight.bold, color: textDark)),
              Container(
                padding: const EdgeInsets.symmetric(horizontal: 8, vertical: 4),
                decoration: BoxDecoration(color: redColor, borderRadius: BorderRadius.circular(20)),
                child: const Text('-2.4%', style: TextStyle(color: Colors.white, fontSize: 12, fontWeight: FontWeight.bold)),
              ),
              Container(
                padding: const EdgeInsets.symmetric(horizontal: 16, vertical: 8),
                decoration: BoxDecoration(color: bgColor, borderRadius: BorderRadius.circular(20)),
                child: const Text('Last 30 Days', style: TextStyle(color: textDark, fontSize: 13, fontWeight: FontWeight.w600)),
              )
            ],
          ),
          const SizedBox(height: 40),
          Expanded(
            child: BarChart(
              BarChartData(
                alignment: BarChartAlignment.spaceAround,
                maxY: maxY,
                barTouchData: BarTouchData(enabled: false),
                titlesData: FlTitlesData(
                  show: true,
                  bottomTitles: AxisTitles(
                    sideTitles: SideTitles(
                      showTitles: true,
                      getTitlesWidget: (value, meta) {
                        List<String> labels = ['W1', 'W2', 'W3', 'W4', 'W5', 'W6'];
                        return Padding(
                          padding: const EdgeInsets.only(top: 10.0),
                          child: Text(labels[value.toInt()], style: const TextStyle(color: textMuted, fontSize: 12, fontWeight: FontWeight.w500)),
                        );
                      },
                    ),
                  ),
                  leftTitles: AxisTitles(
                    sideTitles: SideTitles(
                      showTitles: true,
                      reservedSize: 50,
                      interval: maxY / 4 == 0 ? 1 : maxY / 4,
                      getTitlesWidget: (value, meta) {
                        if (value == 0) return const Text('RM 0', style: TextStyle(color: textMuted, fontSize: 12));
                        if (value == maxY) return const SizedBox.shrink();
