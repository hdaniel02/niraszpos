class _TimelineScrollSync extends StatefulWidget {
  final List<Map<String, dynamic>> items;
  const _TimelineScrollSync({required this.items});

  @override
  State<_TimelineScrollSync> createState() => _TimelineScrollSyncState();
}

class _TimelineScrollSyncState extends State<_TimelineScrollSync> {
  final ScrollController _scrollController = ScrollController();
  double _scrollProgress = 0.0;
  
  static const Color textDark = Color(0xFF111827);
  static const Color textMuted = Color(0xFF6B7280);

  final GlobalKey _greenLineKey = GlobalKey();
  late List<GlobalKey> _itemKeys;
  late List<bool> _isReached;

  @override
  void initState() {
    super.initState();
    _itemKeys = List.generate(widget.items.length, (index) => GlobalKey());
    _isReached = List.generate(widget.items.length, (index) => index == 0);

    _scrollController.addListener(() {
      if (_scrollController.position.maxScrollExtent > 0) {
        setState(() {
          _scrollProgress = (_scrollController.offset / _scrollController.position.maxScrollExtent).clamp(0.0, 1.0);
          _checkIntersections();
        });
      }
    });

    WidgetsBinding.instance.addPostFrameCallback((_) {
      setState(() {
        _checkIntersections();
      });
    });
  }

  void _checkIntersections() {
    if (_greenLineKey.currentContext == null) return;
    final greenBox = _greenLineKey.currentContext!.findRenderObject() as RenderBox?;
    if (greenBox == null) return;
    
    // Absolute Y position of the tip of the green line
    double greenTipY = greenBox.localToGlobal(Offset(0, greenBox.size.height)).dy;

    for (int i = 1; i < widget.items.length; i++) {
      final itemContext = _itemKeys[i].currentContext;
      if (itemContext != null) {
        final itemBox = itemContext.findRenderObject() as RenderBox?;
        if (itemBox != null) {
          // Center of the 32x32 icon container
          double itemCenterY = itemBox.localToGlobal(const Offset(0, 16)).dy;
          _isReached[i] = greenTipY >= itemCenterY || _scrollProgress >= 0.99;
        }
      }
    }
  }

  @override
  void dispose() {
    _scrollController.dispose();
    super.dispose();
  }

  IconData _getIcon(String iconName) {
    switch (iconName) {
      case 'chart': return Icons.bar_chart_rounded;
      case 'trending_up': return Icons.trending_up_rounded;
      case 'inventory_2': return Icons.inventory_2_rounded;
      case 'lightbulb': return Icons.lightbulb_outline_rounded;
      default: return Icons.circle;
    }
  }

